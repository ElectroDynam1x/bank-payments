def seed(db: Session) -> None:
    if db.query(User).count() == 0:
        for username, full_name, role in USERS:
            db.add(User(username=username, full_name=full_name, role=role,
                        password_hash=hash_password(settings.demo_password)))
        log.info("Добавлены тестовые пользователи: %s", len(USERS))
    if db.query(Account).count() == 0:
        accounts = [Account(number=n, owner_name=o, balance=Decimal(b)) for n, o, b in ACCOUNTS]
        db.add_all(accounts)
        db.flush()
        for idx, name, acc, bik, amount, purpose, status in PAYMENTS:
            db.add(Payment(account_id=accounts[idx].id, beneficiary_name=name,
                           beneficiary_account=acc, beneficiary_bik=bik,
                           amount=Decimal(amount), purpose=purpose, status=status,
                           created_by="operator"))
        log.info("Добавлены тестовые счета (%s) и поручения (%s)", len(ACCOUNTS), len(PAYMENTS))
